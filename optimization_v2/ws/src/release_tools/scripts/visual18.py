"""Opt-in presentation skin; preserves every non-visual SDF element exactly.

Procedural local assets, no downloaded meshes or hidden runtime dependencies.
Sensor images and GPU lidar may change: physics equality is not sensor equality.
"""
from common18 import *
import copy,math,argparse
import numpy as np
from PIL import Image,ImageDraw
from xml.etree import ElementTree as E
ASSETS=BASE/'assets/presentation_v1'

def physical_signature(root):
    root=copy.deepcopy(root)
    for parent in root.iter():
        for child in list(parent):
            if child.tag=='visual':parent.remove(child)
    xml=E.canonicalize(E.tostring(root,encoding='unicode'),strip_text=True)
    return hashlib.sha256(xml.encode()).hexdigest()

def material(visual,color,texture=None,metal=.0,rough=.8):
    old=visual.find('material')
    if old is not None:visual.remove(old)
    m=E.SubElement(visual,'material')
    for name in ['ambient','diffuse']:E.SubElement(m,name).text=color
    pbr=E.SubElement(E.SubElement(m,'pbr'),'metal')
    E.SubElement(pbr,'metalness').text=str(metal);E.SubElement(pbr,'roughness').text=str(rough)
    if texture:E.SubElement(pbr,'albedo_map').text=str(texture)

def visual_box(parent,name,size,pose,color,metal=0.,rough=.8):
    v=E.SubElement(parent,'visual',name=name);E.SubElement(v,'pose').text=' '.join(map(str,pose))
    E.SubElement(E.SubElement(E.SubElement(v,'geometry'),'box'),'size').text=' '.join(map(str,size))
    material(v,color,metal=metal,rough=rough);return v

def assets():
    ASSETS.mkdir(parents=True,exist_ok=True);rng=np.random.default_rng(18141)
    for name,color in [('grass',[82,111,52]),('soil',[119,98,71]),('gravel',[131,139,141])]:
        noise=rng.normal(0,8,(512,512,1));coarse=np.repeat(np.repeat(rng.normal(0,4,(64,64,1)),8,0),8,1)
        a=np.clip(np.array(color)+noise+coarse,0,255).astype('uint8');im=Image.fromarray(a);d=ImageDraw.Draw(im)
        for _ in range(2300 if name=='grass' else 900):
            x,y=rng.integers(0,512,2);light=int(rng.integers(-20,21));c=tuple(int(np.clip(v+light,0,255)) for v in color)
            if name=='grass':d.line((int(x),int(y),int(x)+int(rng.integers(-2,3)),int(y)+int(rng.integers(2,7))),fill=c,width=1)
            else:d.ellipse((int(x),int(y),int(x)+3,int(y)+2),fill=c)
        im.save(ASSETS/(name+'.png'))
    # A bevelled shell in normalized [-.5,.5]^3; visual scaling matches original box.
    ring=[(-.42,-.5),(.42,-.5),(.5,-.42),(.5,.42),(.42,.5),(-.42,.5),(-.5,.42),(-.5,-.42)]
    vertices=[(x,y,-.5) for x,y in ring]+[(.94*x,.94*y,.48) for x,y in ring]
    faces=[tuple(range(8,0,-1)),tuple(range(9,17))]+[(i+1,(i+1)%8+1,(i+1)%8+9,i+9) for i in range(8)]
    obj=['# original procedural shell']+['v '+' '.join(map(str,v)) for v in vertices]
    for i,face in enumerate(faces,1):
        a,b,c=[np.array(vertices[j-1]) for j in face[:3]];normal=np.cross(b-a,c-a);normal=normal/np.linalg.norm(normal)
        obj.append('vn '+' '.join(map(str,normal)))
        for k in range(1,len(face)-1):obj.append('f '+' '.join(str(j)+'//'+str(i) for j in [face[0],face[k],face[k+1]]))
    (ASSETS/'shell.obj').write_text('\n'.join(obj)+'\n')
    (ASSETS/'PROVENANCE.txt').write_text('Original procedural assets generated by visual18.py, seed 18141. No external images or meshes. Repository licensing applies. Physics is unchanged; sensor qualification is separate.\n')
    return ASSETS

def uv_mesh(source):
    source=Path(source);lines=source.read_text().splitlines();vertices=[list(map(float,l.split()[1:4])) for l in lines if l.startswith('v ')]
    out=[l for l in lines if not l.startswith(('vt ','f ','mtllib ','usemtl '))]
    out+=['vt '+str(v[0]/2)+' '+str(v[1]/2) for v in vertices]
    for l in lines:
        if not l.startswith('f '):continue
        face=[]
        for token in l.split()[1:]:
            bits=token.split('/');idx=int(bits[0]);idx=idx if idx>0 else len(vertices)+idx+1
            face.append(str(idx)+'/'+str(idx)+('/'+bits[2] if len(bits)>2 and bits[2] else ''))
        out.append('f '+' '.join(face))
    dest=ASSETS/(source.stem+'_uv.obj');dest.write_text('\n'.join(out)+'\n');return dest

def apply(source,destination):
    source=Path(source).resolve();destination=Path(destination).resolve()
    if source==destination or not destination.is_relative_to(BASE):raise ValueError('ISOLATED_VISUAL_OUTPUT_REQUIRED')
    if not (ASSETS/'shell.obj').exists():assets()
    tree=E.parse(source);root=tree.getroot();before=physical_signature(root);world=root.find('world')
    if world is None:raise ValueError('WORLD_REQUIRED')
    changed=[]
    for model in world.findall('model'):
        name=model.get('name','')
        for v in model.findall('.//visual'):
            if name in ['spray_workspace','mowing_workspace','connector'] or name.startswith('grade_'):
                tex='gravel' if name=='connector' else 'grass' if name=='mowing_workspace' else 'soil'
                uri=v.find('geometry/mesh/uri')
                if uri is not None:
                    path=Path(uri.text.removeprefix('file://'))
                    if not path.resolve().is_relative_to(BASE/'assets'):raise ValueError('FOREIGN_MESH')
                    uri.text='file://'+str(uv_mesh(path))
                material(v,'1 1 1 1',ASSETS/(tex+'.png'),rough=.98);changed.append(name)
            elif name=='ground':material(v,'.19 .28 .13 1',rough=1.)
            elif name in ['pump_house','shed','utility']:material(v,'.48 .52 .47 1',rough=.9)
            elif name.startswith('unknown_low'):material(v,'.47 .43 .36 1',ASSETS/'gravel.png',rough=.96)
            elif name.startswith('ped_'):
                material(v,'.92 .55 .12 1' if 'body' in v.get('name','') else '.21 .25 .30 1',rough=.9)
        if name!='vehicle':continue
        body=model.find("link[@name='base_link']");v=body.find("visual[@name='body_visual']") if body is not None else None
        if v is None:continue
        original_size=v.findtext('geometry/box/size');pose=list(map(float,v.findtext('pose').split()))
        if not original_size:raise ValueError('KNOWN_BODY_BOX_REQUIRED')
        dims=list(map(float,original_size.split()));g=v.find('geometry');g.clear();mesh=E.SubElement(g,'mesh')
        E.SubElement(mesh,'uri').text='file://'+str(ASSETS/'shell.obj');E.SubElement(mesh,'scale').text=original_size
        ack=model.find("joint[@name='steer_left_joint']") is not None
        material(v,'.055 .25 .18 1' if ack else '.045 .21 .36 1',metal=.22,rough=.36)
        top=pose[2]+dims[2]/2
        visual_box(body,'s18_service_cover',[dims[0]*.45,dims[1]*.63,.004],[pose[0]-.08,0,top-.004,0,0,0],'.10 .13 .15 1',.15,.5)
        for side in [-1,1]:
            visual_box(body,'s18_reflector_'+str(side),[.07,.006,.04],[pose[0]+dims[0]*.37,side*(dims[1]/2-.005),pose[2],0,0,0],'.98 .66 .13 1',.15,.38)
        for i in range(7):
            visual_box(body,'s18_vent_'+str(i),[.012,dims[1]*.37,.001],[pose[0]-.2+i*.045,0,top-.0007,0,0,0],'.025 .035 .04 1',.05,.75)
        for link in model.findall('link'):
            for w in list(link.findall('visual')):
                if 'wheel' in link.get('name',''):
                    material(w,'.035 .04 .045 1',rough=.96)
                    cyl=w.find('geometry/cylinder')
                    if cyl is not None:
                        radius=float(cyl.findtext('radius'));width=float(cyl.findtext('length'))
                        hub=copy.deepcopy(w);hub.set('name',w.get('name')+'_s18_hub');hub.find('geometry/cylinder/radius').text=str(radius*.53)
                        hub.find('geometry/cylinder/length').text=str(width+.001);material(hub,'.48 .51 .54 1',metal=.7,rough=.32);link.append(hub)
                elif link.get('name')=='tool_link':material(w,'.74 .46 .09 1',metal=.15,rough=.58)
        changed.append('vehicle shell, wheels, vents, reflectors, tool')
    after=physical_signature(root)
    if before!=after:raise ValueError('NONVISUAL_PHYSICS_OR_SENSOR_CHANGE')
    destination.parent.mkdir(parents=True,exist_ok=True);E.indent(tree);tree.write(destination,encoding='utf-8',xml_declaration=True)
    # Compare the actual serialized output as well, rather than just the tree.
    if physical_signature(E.parse(destination).getroot())!=before:raise ValueError('SERIALIZED_PHYSICS_CHANGED')
    result=dict(source=str(source.relative_to(ROOT)),destination=str(destination.relative_to(ROOT)),source_sha256=sha(source),
        destination_sha256=sha(destination),nonvisual_signature=before,nonvisual_unchanged=True,
        changed=sorted(set(changed)),sensor_equivalence='NOT_QUALIFIED',autonomous_motion='NOT_RUN',
        assets={str(p.relative_to(ROOT)):sha(p) for p in sorted(ASSETS.iterdir()) if p.is_file()})
    dump(destination.with_suffix('.visual.json'),result);return result

if __name__=='__main__':
    ap=argparse.ArgumentParser();ap.add_argument('--source',type=Path);ap.add_argument('--out',type=Path);a=ap.parse_args()
